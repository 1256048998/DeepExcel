# Build the native side tools: DeepExcel.Repair.exe, DeepExcel.Probe32.exe and
# DeepExcel.Updater.exe.
#
# The first two replace the powershell.exe hops that register-user.ps1 used to
# perform during installation. Repair.exe is AnyCPU (64-bit at runtime);
# Probe32.exe is deliberately x86 because a process can only activate COM in
# its own bitness and 32-bit Office is still common.
#
# Updater.exe installs a staged, signature-verified update after Excel exits.
# It shares the Updates/ sources with the add-in but links against GAC
# assemblies only, because it runs as a lone file copied into the staging
# directory -- see src/DeepExcel.Updater/Program.cs.
#
# Run after scripts\_compile_only.ps1 -- the assembly version is read from the
# freshly built add-in so the repair tool always reports the matching version.

param([string]$OutputDir)

$ErrorActionPreference = 'Stop'
$baseDir = Resolve-Path "$PSScriptRoot\.."
$repairDir = Join-Path $baseDir 'src\DeepExcel.Repair'
$probeDir = Join-Path $baseDir 'src\DeepExcel.Probe32'
$outDir = if ($OutputDir) { [IO.Path]::GetFullPath($OutputDir) } else { Join-Path $baseDir 'src\DeepExcel.AddIn\bin\Release' }
$csc = Join-Path $baseDir 'packages\Microsoft.Net.Compilers.3.8.0\tools\csc.exe'

if (-not (Test-Path $csc)) { throw "Roslyn compiler not found: $csc" }
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

$addinDll = Join-Path $outDir 'DeepExcel.AddIn.dll'
if (-not (Test-Path $addinDll)) {
    throw "DeepExcel.AddIn.dll not found in $outDir. Run scripts\_compile_only.ps1 first."
}
$version = [System.Reflection.AssemblyName]::GetAssemblyName($addinDll).Version.ToString()
Write-Host "Building repair tools for assembly version $version"

# Version stamp is generated, never checked in, so it cannot drift from the
# add-in the way the old hardcoded 0.2.4.0 registration did.
function New-AssemblyInfo {
    param([string]$Title, [string]$Tag)
    $path = Join-Path $env:TEMP "DeepExcel.$Tag.AssemblyInfo.$PID.cs"
    @"
// Generated by scripts/build-repair.ps1 -- do not edit, do not commit.
using System.Reflection;
using System.Runtime.InteropServices;

[assembly: AssemblyTitle("$Title")]
[assembly: AssemblyProduct("DeepExcel")]
[assembly: AssemblyCompany("DeepExcel")]
[assembly: AssemblyVersion("$version")]
[assembly: AssemblyFileVersion("$version")]
[assembly: ComVisible(false)]
"@ | Set-Content -LiteralPath $path -Encoding UTF8
    return $path
}

$generatedInfo = New-AssemblyInfo -Title 'DeepExcel 诊断与修复' -Tag 'Repair'
$generatedUpdaterInfo = New-AssemblyInfo -Title 'DeepExcel 更新程序' -Tag 'Updater'

$fx = 'C:\Windows\Microsoft.NET\Framework64\v4.0.30319'
$commonRefs = @(
    "/reference:`"$fx\mscorlib.dll`"",
    "/reference:`"$fx\System.dll`"",
    "/reference:`"$fx\System.Core.dll`""
)

function Invoke-Csc {
    param([string[]]$Arguments, [string]$Label)
    Write-Host "  csc -> $Label"
    & $csc $Arguments 2>&1 | ForEach-Object { Write-Host "    $_" }
    if ($LASTEXITCODE -ne 0) { throw "$Label build failed (exit $LASTEXITCODE)" }
}

try {
    # ---- DeepExcel.Repair.exe (AnyCPU, winexe so double-click shows no console)
    $repairSources = Get-ChildItem -Path $repairDir -Filter '*.cs' -File | ForEach-Object { $_.FullName }
    if (-not $repairSources) { throw "No sources found in $repairDir" }

    $repairArgs = @(
        '/target:winexe',
        "/out:`"$outDir\DeepExcel.Repair.exe`"",
        '/langversion:9.0',
        '/optimize',
        '/debug:pdbonly',
        '/platform:anycpu',
        "/win32manifest:`"$repairDir\app.manifest`""
    ) + $commonRefs + @(
        "/reference:`"$fx\System.Drawing.dll`"",
        "/reference:`"$fx\System.Windows.Forms.dll`"",
        "/reference:`"$fx\System.IO.Compression.dll`"",
        "/reference:`"$fx\System.IO.Compression.FileSystem.dll`""
    )
    foreach ($f in $repairSources) { $repairArgs += "`"$f`"" }
    $repairArgs += "`"$generatedInfo`""
    Invoke-Csc -Arguments $repairArgs -Label 'DeepExcel.Repair.exe'

    # ---- DeepExcel.Probe32.exe (x86 on purpose; see Probe32/Program.cs)
    $probeArgs = @(
        '/target:exe',
        "/out:`"$outDir\DeepExcel.Probe32.exe`"",
        '/langversion:9.0',
        '/optimize',
        '/debug-',
        '/platform:x86',
        "/win32manifest:`"$repairDir\app.manifest`""
    ) + $commonRefs + @(
        "`"$probeDir\Program.cs`"",
        "`"$repairDir\ComProbe.cs`"",
        "`"$repairDir\AddInIdentity.cs`"",
        "`"$generatedInfo`""
    )
    Invoke-Csc -Arguments $probeArgs -Label 'DeepExcel.Probe32.exe'

    # ---- DeepExcel.Updater.exe (AnyCPU, winexe: a successful update is silent)
    #
    # Compiles the same Updates/ sources the add-in uses, so the manifest that
    # gets verified before installing is verified by the same code that verified
    # it before downloading. References are GAC-only on purpose: this binary is
    # copied out of the install directory and run alone, because Inno Setup
    # cannot overwrite a running executable.
    $updaterDir = Join-Path $baseDir 'src\DeepExcel.Updater'
    $sharedUpdateSources = @(
        'ReleaseVersion.cs',
        'UpdateSigning.cs',
        'UpdateManifest.cs',
        'UpdateStage.cs'
    ) | ForEach-Object { Join-Path $baseDir "src\DeepExcel.AddIn\Updates\$_" }
    foreach ($shared in $sharedUpdateSources) {
        if (-not (Test-Path $shared)) { throw "Missing shared update source: $shared" }
    }

    $updaterArgs = @(
        '/target:winexe',
        "/out:`"$outDir\DeepExcel.Updater.exe`"",
        '/langversion:9.0',
        '/optimize',
        '/debug:pdbonly',
        '/platform:anycpu',
        "/win32manifest:`"$updaterDir\app.manifest`""
    ) + $commonRefs + @(
        "/reference:`"$fx\System.Windows.Forms.dll`"",
        "/reference:`"$fx\System.Web.Extensions.dll`""
    )
    $updaterArgs += "`"$updaterDir\Program.cs`""
    foreach ($f in $sharedUpdateSources) { $updaterArgs += "`"$f`"" }
    $updaterArgs += "`"$generatedUpdaterInfo`""
    Invoke-Csc -Arguments $updaterArgs -Label 'DeepExcel.Updater.exe'
}
finally {
    Remove-Item -LiteralPath $generatedInfo -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $generatedUpdaterInfo -Force -ErrorAction SilentlyContinue
}

# Guard the one mistake that would make the 32-bit probe silently useless:
# an AnyCPU build would run 64-bit and report a false pass.
Add-Type -AssemblyName System.Core
$probeExe = Join-Path $outDir 'DeepExcel.Probe32.exe'
$peKind = New-Object System.Reflection.PortableExecutableKinds
$machine = New-Object System.Reflection.ImageFileMachine
[System.Reflection.Assembly]::ReflectionOnlyLoadFrom($probeExe).ManifestModule.GetPEKind([ref]$peKind, [ref]$machine)
if ($machine -ne [System.Reflection.ImageFileMachine]::I386 -or
    ($peKind -band [System.Reflection.PortableExecutableKinds]::Required32Bit) -eq 0) {
    throw "DeepExcel.Probe32.exe is not a 32-bit image (machine=$machine kind=$peKind)"
}

Write-Host ''
Write-Host '=== NATIVE TOOLS BUILD SUCCESS ==='
Get-Item "$outDir\DeepExcel.Repair.exe", $probeExe, "$outDir\DeepExcel.Updater.exe" |
    Select-Object Name, Length, LastWriteTime
